// No organization_id column — these hang off an engagement / session, so they go
// child-first, before agi_engagements itself is deleted.
const CHILDREN = [
  { t: 'agi_transcripts', key: 'session_id', via: 'agi_sessions' },
  { t: 'agi_actions', key: 'session_id', via: 'agi_sessions' },
];

const arr = PLATFORM.map((t) => `'${t}'`).join(', ');

const childBlocks = CHILDREN.map((c) => `  SELECT count(*) INTO n FROM ${c.t} x
    JOIN ${c.via} v ON v.id = x.${c.key}
    JOIN agi_engagements e ON e.id = v.engagement_id
   WHERE e.organization_id = 4;
  total := total + n;
  RAISE NOTICE '  [child] % %', rpad('${c.t}', 34), n;
  IF __APPLY__ AND n > 0 THEN
    DELETE FROM ${c.t} WHERE ${c.key} IN (
      SELECT v.id FROM ${c.via} v JOIN agi_engagements e ON e.id = v.engagement_id
       WHERE e.organization_id = 4);
  END IF;`).join('\n\n');

const HEAD = (what) => `-- generated by gen-purge.cjs — ${what}
\\set ON_ERROR_STOP on
\\set QUIET 0
\\pset pager off
SET client_min_messages TO notice;
\\if :apply
\\echo '*** APPLY ***'
\\else
\\echo '*** PLAN (rolls back) ***'
\\endif
BEGIN;
`;

const platformSql = HEAD('org-4 platform data') + `
DO $$
DECLARE n bigint; total bigint := 0;
BEGIN
${childBlocks}

  -- agi_sessions sits between actions/transcripts and the engagement
  SELECT count(*) INTO n FROM agi_sessions s
    JOIN agi_engagements e ON e.id = s.engagement_id WHERE e.organization_id = 4;
  total := total + n;
  RAISE NOTICE '  [child] % %', rpad('agi_sessions', 34), n;
  IF __APPLY__ AND n > 0 THEN
    DELETE FROM agi_sessions WHERE engagement_id IN (
      SELECT id FROM agi_engagements WHERE organization_id = 4);
  END IF;

  RAISE NOTICE '  [child] subtotal %', total;
END $$;

DO $$
DECLARE t text; n bigint; total bigint := 0;
        tbls text[] := ARRAY[${arr}];
        absent int := 0; noorg int := 0; hit int := 0;
BEGIN
  FOREACH t IN ARRAY tbls LOOP
    IF to_regclass('public.' || quote_ident(t)) IS NULL THEN absent := absent + 1; CONTINUE; END IF;
    IF NOT EXISTS (SELECT 1 FROM information_schema.columns
                   WHERE table_schema = 'public' AND table_name = t
                     AND column_name = 'organization_id') THEN
      noorg := noorg + 1;
      RAISE NOTICE '  [skip ] % (no organization_id)', rpad(t, 34);
      CONTINUE;
    END IF;
    EXECUTE format('SELECT count(*) FROM public.%I WHERE organization_id = 4', t) INTO n;
    total := total + n;
    IF n > 0 THEN
      hit := hit + 1;
      RAISE NOTICE '  [rows ] % %', rpad(t, 34), n;
      IF __APPLY__ THEN
        EXECUTE format('DELETE FROM public.%I WHERE organization_id = 4', t);
      END IF;
    END IF;
  END LOOP;
  RAISE NOTICE '  [platform] listed=% absent=% no_org_col=% tables_with_rows=% rows=%',
    array_length(tbls, 1), absent, noorg, hit, total;
END $$;

\\if :apply
COMMIT;
\\else
ROLLBACK;
\\endif
`;

const securitySql = HEAD('org-4 security schema') + `
DO $$
DECLARE t text; n bigint; total bigint := 0; tbls text;
        keep text[] := ARRAY['schema_migrations','soc_detection_rules'];
        ntab int := 0;
BEGIN
  SELECT string_agg(quote_ident(tablename), ', ') INTO tbls
    FROM pg_tables WHERE schemaname = 'phantix' AND NOT (tablename = ANY(keep));
  IF tbls IS NULL THEN RAISE NOTICE '  [security] nothing to clear'; RETURN; END IF;

  FOR t IN SELECT tablename FROM pg_tables
            WHERE schemaname = 'phantix' AND NOT (tablename = ANY(keep)) LOOP
    EXECUTE format('SELECT count(*) FROM phantix.%I', t) INTO n;
    total := total + n; ntab := ntab + 1;
    IF n > 0 THEN RAISE NOTICE '  [rows ] % %', rpad(t, 34), n; END IF;
  END LOOP;
  RAISE NOTICE '  [security] tables=% rows=%', ntab, total;

  IF __APPLY__ THEN
    EXECUTE 'TRUNCATE ' || tbls || ' RESTART IDENTITY CASCADE';
  END IF;
END $$;

\\if :apply
COMMIT;
\\else
ROLLBACK;
\\endif
`;

fs.writeFileSync(path.join(__dirname, 'purge-platform.sql'), platformSql);
fs.writeFileSync(path.join(__dirname, 'purge-security.sql'), securitySql);
console.log(`purge-platform.sql: ${PLATFORM.length} listed + ${CHILDREN.length + 1} child tables, flag=__APPLY__`);
console.log('purge-security.sql: every phantix.* table except schema_migrations, soc_detection_rules');
