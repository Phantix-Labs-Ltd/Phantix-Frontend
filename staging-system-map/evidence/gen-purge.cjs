#!/usr/bin/env node
/**
 * gen-purge.cjs — writes explicit SQL templates instead of building SQL from
 * nested bash heredocs.
 *
 *   purge-platform.sql   org-4 rows in the shared platform DB
 *   purge-security.sql   the org's own schema in the security DB
 *
 * IMPORTANT: psql does NOT interpolate :variables inside $$ dollar-quoted
 * blocks, so the apply flag is a literal placeholder (__APPLY__) that the runner
 * substitutes with sed, while \if :apply only controls COMMIT vs ROLLBACK.
 */
const fs = require('fs');
const path = require('path');

// Platform tables holding org-4 tenant data.
